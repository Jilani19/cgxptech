import nodemailer from 'nodemailer';
import Contact from '../models/Contact.js';

export const submitContactForm = async (req, res) => {
  const { name, email, company, industry, message } = req.body;

  // Basic validation
  if (!name || !email || !company || !industry || !message) {
    return res.status(400).json({ message: 'All contact fields are required.' });
  }

  try {
    // Save to Database
    const newContact = new Contact({ name, email, company, industry, message });
    await newContact.save();

    console.log(`Saved contact form submission from: ${name} (${email})`);

    // Prepare email parameters
    const smtpHost = process.env.SMTP_HOST;
    const smtpPort = parseInt(process.env.SMTP_PORT || '587');
    const smtpUser = process.env.SMTP_USER;
    const smtpPass = process.env.SMTP_PASS;
    const recipient = process.env.CONTACT_RECIPIENT || 'hello@cgxptech.com';

    const isPlaceholder = !smtpUser || smtpUser.includes('your_email') || smtpPass.includes('your_app_password');

    let emailSent = false;
    let transportMethod = 'Mock Logger';

    if (!isPlaceholder) {
      try {
        const transporter = nodemailer.createTransport({
          host: smtpHost,
          port: smtpPort,
          secure: smtpPort === 465, // True for 465, false for 587
          auth: {
            user: smtpUser,
            pass: smtpPass,
          },
        });

        const mailOptions = {
          from: `"cGxP Tech Contact Hub" <${smtpUser}>`,
          to: recipient,
          subject: `🚀 New Contact Form Submission from ${company}`,
          html: `
            <h2>New Inquiry for cGxP Tech</h2>
            <p><strong>Name:</strong> ${name}</p>
            <p><strong>Email:</strong> ${email}</p>
            <p><strong>Company:</strong> ${company}</p>
            <p><strong>Industry Focus:</strong> ${industry}</p>
            <p><strong>Message:</strong></p>
            <blockquote style="background: #f1f5f9; padding: 12px; border-left: 4px solid #00C4B4;">
              ${message.replace(/\n/g, '<br/>')}
            </blockquote>
            <hr/>
            <p style="font-size: 11px; color: #64748b;">This message was automatically generated by cGxP Tech Platform API.</p>
          `,
        };

        const info = await transporter.sendMail(mailOptions);
        console.log(`Contact email dispatched successfully: ${info.messageId}`);
        emailSent = true;
        transportMethod = 'SMTP Server';
      } catch (nodemailerErr) {
        console.error(`Nodemailer failure (SMTP dispatch failed): ${nodemailerErr.message}`);
        // Do not crash the API, fallback to logging
      }
    }

    if (!emailSent) {
      // Graceful fallback logger
      console.log('--- SIMULATED NODEMAILER TRANSMISSION ---');
      console.log(`From: cGxP Tech Hub`);
      console.log(`To: ${recipient}`);
      console.log(`Subject: [MOCK] Contact Inquiry - ${company}`);
      console.log(`Body:\nName: ${name}\nEmail: ${email}\nCompany: ${company}\nIndustry: ${industry}\nMessage: ${message}`);
      console.log('-----------------------------------------');
    }

    res.status(201).json({
      message: 'Thank you for reaching out! Our team of life sciences experts will contact you shortly.',
      contactId: newContact._id,
      emailDispatched: emailSent || isPlaceholder,
      deliveryMethod: transportMethod
    });

  } catch (error) {
    res.status(500).json({ message: 'Error processing contact form inquiry', error: error.message });
  }
};
